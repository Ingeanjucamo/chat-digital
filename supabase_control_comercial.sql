-- ================================================================
-- CONTROL COMERCIAL: METAS + NOVEDADES / DESCUENTOS
-- Solo el SuperAdmin puede modificar la configuración.
-- ================================================================

CREATE TABLE IF NOT EXISTS public.metas_comerciales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asesor_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  anio integer NOT NULL,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  meta numeric(10,2) NOT NULL DEFAULT 45,
  activo boolean NOT NULL DEFAULT true,
  creado_por bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  actualizado_por bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT metas_comerciales_asesor_mes_unique UNIQUE (asesor_id, anio, mes)
);

CREATE TABLE IF NOT EXISTS public.novedades_comerciales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asesor_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  fecha date NOT NULL,
  anio integer NOT NULL,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  tipo text NOT NULL DEFAULT 'Otro',
  motivo text NOT NULL,
  descuento numeric(10,2) NOT NULL DEFAULT 1 CHECK (descuento >= 0),
  observacion text NULL,
  venta_id bigint NULL REFERENCES public.ventas(id) ON DELETE SET NULL,
  cliente_nombre text NULL,
  cliente_numero text NULL,
  activo boolean NOT NULL DEFAULT true,
  creado_por bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_metas_comerciales_mes
  ON public.metas_comerciales(anio, mes, asesor_id);

CREATE INDEX IF NOT EXISTS idx_novedades_comerciales_mes
  ON public.novedades_comerciales(anio, mes, asesor_id, activo);

-- Si la tabla ya existía de una versión anterior, completar las columnas nuevas.
ALTER TABLE public.novedades_comerciales
  ADD COLUMN IF NOT EXISTS venta_id bigint NULL REFERENCES public.ventas(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS cliente_nombre text NULL,
  ADD COLUMN IF NOT EXISTS cliente_numero text NULL;

CREATE INDEX IF NOT EXISTS idx_novedades_comerciales_venta
  ON public.novedades_comerciales(venta_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_novedades_comerciales_venta_activa
  ON public.novedades_comerciales(venta_id)
  WHERE activo = true AND venta_id IS NOT NULL;

ALTER TABLE public.metas_comerciales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.novedades_comerciales ENABLE ROW LEVEL SECURITY;

-- ================================================================
-- METAS: lectura para el dashboard; escritura únicamente SuperAdmin
-- ================================================================
DROP POLICY IF EXISTS "metas_comerciales_select" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_select"
ON public.metas_comerciales
FOR SELECT TO authenticated
USING (
  asesor_id = public.usuario_actual_id()
  OR public.usuario_actual_rol() IN ('Supervisor','Revisor','Administrador')
  OR public.usuario_es_super_admin()
);

DROP POLICY IF EXISTS "metas_comerciales_insert_superadmin" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_insert_superadmin"
ON public.metas_comerciales
FOR INSERT TO authenticated
WITH CHECK (public.usuario_es_super_admin());

DROP POLICY IF EXISTS "metas_comerciales_update_superadmin" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_update_superadmin"
ON public.metas_comerciales
FOR UPDATE TO authenticated
USING (public.usuario_es_super_admin())
WITH CHECK (public.usuario_es_super_admin());

DROP POLICY IF EXISTS "metas_comerciales_delete_superadmin" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_delete_superadmin"
ON public.metas_comerciales
