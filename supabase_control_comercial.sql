-- ================================================================
-- Mantener updated_at
-- ================================================================
CREATE OR REPLACE FUNCTION public.actualizar_updated_at_control_comercial()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_metas_comerciales_updated_at ON public.metas_comerciales;
CREATE TRIGGER trg_metas_comerciales_updated_at
BEFORE UPDATE ON public.metas_comerciales
FOR EACH ROW EXECUTE FUNCTION public.actualizar_updated_at_control_comercial();

DROP TRIGGER IF EXISTS trg_novedades_comerciales_updated_at ON public.novedades_comerciales;
CREATE TRIGGER trg_novedades_comerciales_updated_at
BEFORE UPDATE ON public.novedades_comerciales
FOR EACH ROW EXECUTE FUNCTION public.actualizar_updated_at_control_comercial();

