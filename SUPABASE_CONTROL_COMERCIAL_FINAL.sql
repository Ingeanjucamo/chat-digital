DROP POLICY IF EXISTS "metas_comerciales_select" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_select"
ON public.metas_comerciales
FOR SELECT TO authenticated
USING (
  asesor_id = public.usuario_actual_id()
  OR public.usuario_actual_rol() IN ('Supervisor','Revisor','Administrador')
  OR public.usuario_es_super_admin()
);

DROP POLICY IF EXISTS "metas_comerciales_insert_superadmin" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_insert_superadmin"
ON public.metas_comerciales
FOR INSERT TO authenticated
WITH CHECK (public.usuario_es_super_admin());

DROP POLICY IF EXISTS "metas_comerciales_update_superadmin" ON public.metas_comerciales;
CREATE POLICY "metas_comerciales_update_superadmin"
ON public.metas_comerciales
FOR UPDATE TO authenticated
USING (public.usuario_es_super_admin())
WITH CHECK (public.usuario_es_super_admin());

