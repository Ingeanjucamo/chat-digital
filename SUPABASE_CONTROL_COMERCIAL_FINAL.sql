CREATE TABLE IF NOT EXISTS public.metas_comerciales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asesor_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  anio integer NOT NULL,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  meta numeric(10,2) NOT NULL DEFAULT 45,
  activo boolean NOT NULL DEFAULT true,
  creado_por bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  actualizado_por bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT metas_comerciales_asesor_mes_unique UNIQUE (asesor_id, anio, mes)
);

CREATE TABLE IF NOT EXISTS public.novedades_comerciales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asesor_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  fecha date NOT NULL,
  anio integer NOT NULL,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  tipo text NOT NULL DEFAULT 'Caída por titular',
  motivo text NOT NULL,
  descuento numeric(10,2) NOT NULL DEFAULT 1 CHECK (descuento >= 0),
  observacion text NULL,
  venta_id bigint NULL REFERENCES public.ventas(id) ON DELETE SET NULL,
  cliente_nombre text NULL,
  cliente_numero text NULL,
  activo boolean NOT NULL DEFAULT true,
  creado_por bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.novedades_comerciales
  ADD COLUMN IF NOT EXISTS venta_id bigint NULL REFERENCES public.ventas(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS cliente_nombre text NULL,
  ADD COLUMN IF NOT EXISTS cliente_numero text NULL;

CREATE INDEX IF NOT EXISTS idx_metas_comerciales_mes
  ON public.metas_comerciales(anio, mes, asesor_id);

CREATE INDEX IF NOT EXISTS idx_novedades_comerciales_mes
  ON public.novedades_comerciales(anio, mes, asesor_id, activo);

CREATE INDEX IF NOT EXISTS idx_novedades_comerciales_venta
  ON public.novedades_comerciales(venta_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_novedades_comerciales_venta_activa
  ON public.novedades_comerciales(venta_id)
  WHERE activo = true AND venta_id IS NOT NULL;

-- ================================================================
-- IDENTIDAD DEL USUARIO
-- Corrige el caso en que un perfil tenga auth_user_id vacío.
-- El login de Chat Digital usa usuario@chat-digital.online.
-- Primero intenta auth_user_id y luego el usuario del correo Auth.
-- ================================================================

CREATE OR REPLACE FUNCTION public.usuario_actual_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT u.id
  FROM public.usuarios u
  WHERE u.auth_user_id = auth.uid()
     OR lower(u.usuario) = lower(split_part(COALESCE(auth.jwt()->>'email',''), '@', 1))
  ORDER BY CASE WHEN u.auth_user_id = auth.uid() THEN 0 ELSE 1 END
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.usuario_actual_rol()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT u.rol
  FROM public.usuarios u
  WHERE u.auth_user_id = auth.uid()
     OR lower(u.usuario) = lower(split_part(COALESCE(auth.jwt()->>'email',''), '@', 1))
  ORDER BY CASE WHEN u.auth_user_id = auth.uid() THEN 0 ELSE 1 END
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.usuario_es_super_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(u.es_super_admin, false)
  FROM public.usuarios u
  WHERE u.auth_user_id = auth.uid()
     OR lower(u.usuario) = lower(split_part(COALESCE(auth.jwt()->>'email',''), '@', 1))
  ORDER BY CASE WHEN u.auth_user_id = auth.uid() THEN 0 ELSE 1 END
  LIMIT 1;
$$;

